/**
 * Simplified world coastlines, as flat [lon, lat, lon, lat, …] rings.
 *
 * Why not an equirectangular PNG? Because the globe is only ~300 px across,
 * so a texture would be 95 % wasted bytes, and because polygons stay crisp at
 * any particle count while a bitmap quantises the sampling. This is ~12 kB of
 * source that ships inside the JS bundle — no extra request, no CORS, no
 * decode step, and it can be sampled at any resolution.
 *
 * Accuracy target: recognisable at globe scale (1° ≈ 0.4 px). Small seas that
 * would be sub-pixel (Black Sea, Caspian, Persian Gulf, Gulf of California)
 * are deliberately filled — carving them would only produce aliasing noise.
 * The Red Sea survives because Africa and Eurasia are separate rings.
 */

