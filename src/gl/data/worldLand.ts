/**
 * Antarctica wraps the antimeridian, so a ring would need special casing.
 * A wobbling latitude threshold is both cheaper and visually indistinguishable
 * at this scale.
 */
export function antarcticaLat(lonDeg: number): number {
  const l = (lonDeg * Math.PI) / 180;
  return -69.5 + 3.2 * Math.sin(l * 3.0 + 0.8) + 1.6 * Math.sin(l * 5.0 - 2.1);
}
